write(
  'README.md',
  [
    '# Stress fixtures',
    '',
    'Generated by `node tests/stress/generate-vault.mjs`. Nothing here is hand written and',
    'nothing outside this folder is touched. Safe to delete at any time; the generator',
    'recreates it.',
    ''
  ].join('\n')
)

const r = rng(20240607)

// 1. One huge document: everything a real note mixes, at volume.
{
  const sections = quick ? 40 : 8000
  const out = ['# Huge document', '', paragraph(r), '']
  for (let i = 0; i < sections; i++) {
    out.push(`## Section ${i}`, '')
    out.push(paragraph(r, 6), '')
    if (i % 3 === 0) {
      out.push(`- ${sentence(r)}`, `- ${sentence(r)}`, `  - nested ${sentence(r, 6)}`, '')
    }
    if (i % 5 === 0) out.push(codeBlock(r, 12), '')
    if (i % 7 === 0) out.push(table(r, 8, 5), '')
    if (i % 11 === 0) out.push('```mermaid', 'graph TD', '  A-->B', '  B-->C', '```', '')
    if (i % 13 === 0) out.push('$$', '\\int_0^1 x^2 \\, dx = \\frac{1}{3}', '$$', '')
    if (i % 17 === 0) out.push(`> [!note]`, `> ${sentence(r)}`, '')
    if (i % 19 === 0) out.push(`- [ ] task ${i}`, `- [x] done ${i}`, '')
    if (i % 23 === 0) out.push(`See [[Huge document#Section ${i}]] and [[Many notes 0001]].`, '')
    if (i % 29 === 0) out.push(`A footnote reference.[^${i}]`, '', `[^${i}]: ${sentence(r)}`, '')
  }
  write('huge-single.md', `${out.join('\n')}\n`)
}

// 2. One enormous table: the cell widget path, at a size no real note reaches.
{
  const rows = quick ? 200 : 4000
  write('huge-table.md', `# Huge table\n\n${table(r, rows, 8)}\n`)
}

// 3. Many diagrams: Mermaid is the heaviest dependency in the app.
{
  const count = quick ? 6 : 60
  const out = ['# Many diagrams', '']
  for (let i = 0; i < count; i++) {
    out.push('```mermaid', 'graph TD', `  N${i}a-->N${i}b`, `  N${i}b-->N${i}c`, '```', '')
  }
  write('many-diagrams.md', `${out.join('\n')}\n`)
}

// 4. Pathological nesting: lists, quotes, emphasis.
{
  const out = ['# Deep nesting', '']
  for (let d = 1; d <= (quick ? 12 : 40); d++) {
    out.push(`${'  '.repeat(d)}- level ${d} ${sentence(r, 4)}`)
  }
  out.push('')
  for (let d = 1; d <= (quick ? 8 : 30); d++) {
    out.push(`${'> '.repeat(d)}quoted level ${d}`)
  }
  out.push('')
  out.push(`${'*'.repeat(quick ? 20 : 120)}emphasis${'*'.repeat(quick ? 20 : 120)}`)
  out.push(`${'_'.repeat(quick ? 20 : 120)}underscore${'_'.repeat(quick ? 20 : 120)}`)
  write('deep-nesting.md', `${out.join('\n')}\n`)
}

// 5. Very long lines: the classic line-index blowup.
{
  const lines = quick ? 4 : 20
  const width = quick ? 20000 : 200000
  const out = ['# Long lines', '']
  for (let i = 0; i < lines; i++) out.push(`${i}: ${'lorem ipsum dolor sit amet '.repeat(Math.ceil(width / 27)).slice(0, width)}`)
  write('long-lines.md', `${out.join('\n')}\n`)
}

// 6. Unicode: graphemes, offsets, and anything that assumes ASCII.
