/**
 * Stress fixture generator.
 *
 * Writes into the real WriteMd vault under `_stress/` and nothing else. The
 * fixtures are deterministic (seeded PRNG, fixed shape) so two runs measure
 * the same work, and every file is regenerated from scratch each time, so the
 * folder is safe to delete whenever.
 *
 *   node tests/stress/generate-vault.mjs            # default sizes
 *   node tests/stress/generate-vault.mjs --quick    # small sizes, for smoke runs
 *   node tests/stress/generate-vault.mjs --vault D  # override the vault root
 */
import { mkdirSync, rmSync, writeFileSync } from 'fs'
import { homedir } from 'os'
import { join } from 'path'

const args = process.argv.slice(2)
const quick = args.includes('--quick')
const vaultFlag = args.indexOf('--vault')
const VAULT =
  vaultFlag >= 0 && args[vaultFlag + 1]
    ? args[vaultFlag + 1]
    : join(homedir(), 'Documents', 'WriteMd Vault')
const ROOT = join(VAULT, '_stress')

/** mulberry32: tiny, seeded, good enough for fixture text. */
function rng(seed) {
  let a = seed >>> 0
  return () => {
    a = (a + 0x6d2b79f5) >>> 0
    let t = Math.imul(a ^ (a >>> 15), 1 | a)
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

const WORDS = [
  'alpha','beta','gamma','delta','epsilon','zeta','eta','theta','iota','kappa','lambda','mu',
  'nu','xi','omicron','pi','rho','sigma','tau','upsilon','phi','chi','psi','omega','render',
  'parse','viewport','selection','decoration','transaction','listener','subscription','scroll',
  'measure','layout','paint','composite','raster','shader','buffer','texture','atlas','glyph',
  'metric','baseline','regression','fixture','harness','threshold','budget','latency','frame'
]

function sentence(r, words = 12) {
  const out = []
  for (let i = 0; i < words; i++) out.push(WORDS[Math.floor(r() * WORDS.length)])
  const s = out.join(' ')
  return s.charAt(0).toUpperCase() + s.slice(1) + '.'
}

function paragraph(r, sentences = 4) {
  const out = []
  for (let i = 0; i < sentences; i++) out.push(sentence(r))
  return out.join(' ')
}

function codeBlock(r, lines) {
  const out = ['```ts']
  for (let i = 0; i < lines; i++) {
    out.push(`export const value${i} = compute(${Math.floor(r() * 1000)}, '${WORDS[Math.floor(r() * WORDS.length)]}')`)
  }
  out.push('```')
  return out.join('\n')
}

function table(r, rows, cols) {
  const head = ['| ' + Array.from({ length: cols }, (_, c) => `col ${c}`).join(' | ') + ' |']
  const sep = ['|' + Array.from({ length: cols }, () => ' --- ').join('|') + '|']
  const body = []
  for (let i = 0; i < rows; i++) {
    body.push('| ' + Array.from({ length: cols }, () => WORDS[Math.floor(r() * WORDS.length)]).join(' | ') + ' |')
  }
  return [...head, ...sep, ...body].join('\n')
}

function write(name, content) {
  const path = join(ROOT, name)
  mkdirSync(join(path, '..'), { recursive: true })
  writeFileSync(path, content, 'utf-8')
  const bytes = Buffer.byteLength(content)
  console.log(`${name.padEnd(28)} ${(bytes / 1024).toFixed(0).padStart(9)} KB`)
  return bytes
}

