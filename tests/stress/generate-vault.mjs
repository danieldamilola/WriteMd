  out.push('CJK: ' + '_WRITE_MD_STRESS_'.repeat(200) + '')
  out.push('RTL: ' + 'مرحبا بالعالم '.repeat(200) + '')
  out.push('Combining: ' + 'éàô '.repeat(500) + '')
  out.push('Zero width: ' + 'a‍b‌c﻿d'.repeat(500) + '')
  out.push('Surrogates: ' + '𠜎𡈽𩸽'.repeat(300) + '')
